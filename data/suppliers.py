def directory_supplier(
    supplier_id: str,
    name: str,
    category: str,
    best_for: str,
    budget: str,
    gift_fit: str,
    event_fit: str,
    why_useful: str,
    watch_out: str,
    link_label: str,
    tags: list[str],
    contact_url: str | None = None,
    editorial_status: str = "Editorially listed",
    region: str = "UK",
) -> dict:
    """Build supplier-directory data from the central link config."""
    primary_url = supplier_url(supplier_id)
    return {
        "id": supplier_id,
        "name": name,
        "category": category,
        "bestFor": best_for,
        "budget": budget,
        "giftFit": gift_fit,
        "eventFit": event_fit,
        "whyUseful": why_useful,
        "watchOut": watch_out,
        "primaryUrl": primary_url,
        "contactUrl": contact_url or supplier_canonical_url(supplier_id) or primary_url,
        "linkLabel": link_label,
        "region": region,
        "editorialStatus": editorial_status,
        "tags": tags,
        "isAffiliate": bool(supplier_affiliate_url(supplier_id)),
        "affiliateUrl": supplier_affiliate_url(supplier_id),
    }


